def n(x):
    if isinstance(x, F):
        if x.denominator == 1: return n(x.numerator)
        w, r = divmod(x.numerator, x.denominator)
        return f"{w} {r}/{x.denominator}" if w else f"{x.numerator}/{x.denominator}"
    if isinstance(x, float):
        s = f"{x:,.2f}".rstrip("0").rstrip(".")
        return s
    return f"{x:,}"
def Q(t, q, ans, wr, ex, unit=""):
    """wr = [(ค่าผิด, เหตุผล)]"""
    fmt = lambda v: (n(v) + (" " + unit if unit else "")) if not isinstance(v, str) else v
    A = fmt(ans); opts = []; why = {}
    for v, r in wr:
        s = fmt(v)
        if s != A and s not in opts and (isinstance(v, str) or v >= 0): opts.append(s); why[s] = r
    k = 1
    while len(opts) < 3 and not isinstance(ans, str) and k < 50:  # เติมตัวเลือกให้ครบ 4
        for v in ([ans + k, ans - k] if not isinstance(ans, str) else []):
            s = fmt(v)
            if len(opts) < 3 and s != A and s not in opts and v >= 0: opts.append(s); why[s] = "คำนวณคลาดไป ลองทำใหม่ทีละขั้นตามวิธีคิด"
        k += 1
    if len(opts) < 3: raise ValueError("ตัวเลือกไม่ครบ")
    opts = opts[:3]; c = opts + [A]; R.shuffle(c)
    a = c.index(A)
    return {"t": t, "q": q, "c": c, "a": a, "ex": ex, "w": {str(i): why[s] for i, s in enumerate(c) if i != a}}

