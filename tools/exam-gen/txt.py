import random, json
R = random.Random(20261127)
P = {}  # (subj, grade) -> [items]
def add(s, g, it): P.setdefault((s, g), []).append(it)
def mk(t, q, ans, opts, ex):  # opts = [(ข้อความ, เหตุผล)]
    c = [o for o, _ in opts] + [ans]; R.shuffle(c); a = c.index(ans); why = dict(opts)
    return {"t": t, "q": q, "c": c, "a": a, "ex": ex, "w": {str(i): why[x] for i, x in enumerate(c) if i != a}}
def T(x): return [tuple(l.split("|")) for l in x.strip().split("\n")]
def pairs(s, g, t, rows, qf, fact, qr=None):
    """rows=(k,v) · qf ถาม v จาก k · qr ถาม k จาก v · fact = ประโยคความจริง"""
    F = lambda k, v: fact.format(k=k, v=v)
    for k, v in rows:
        o = [(k2, v2) for k2, v2 in rows if v2 != v]; R.shuffle(o); seen = []; op = []
        for k2, v2 in o:
            if v2 not in seen and len(op) < 3: seen.append(v2); op.append((v2, F(k2, v2)))
        if len(op) == 3: add(s, g, mk(t, qf.format(k=k), v, op, F(k, v)))
        if qr:
            o = [(k2, v2) for k2, v2 in rows if v2 != v and k2 != k]; R.shuffle(o)
            op = [(k2, F(k2, v2)) for k2, v2 in o[:3]]
            if len(op) == 3: add(s, g, mk(t, qr.format(v=v), k, op, F(k, v)))
def cats(s, g, t, rows, qf, fact):
    """rows=(สิ่ง,กลุ่ม) ≥4 กลุ่ม · ถามว่าอยู่กลุ่มใด"""
    allc = list(dict.fromkeys(v for _, v in rows))
    for k, v in rows:
        o = [c for c in allc if c != v]; R.shuffle(o)
        add(s, g, mk(t, qf.format(k=k), v, [(c, fact.format(k=k, v=v) + " ไม่ใช่" + c) for c in o[:3]], fact.format(k=k, v=v)))
def odd(s, g, t, A, la, B, q, n=None):
    """ถาม ‘ข้อใด{la}’ คำตอบจาก A ตัวลวงจาก B (B = [(สิ่ง, ข้อความว่าเป็นอะไร)])"""
    for x in (A if n is None else R.sample(A, min(n, len(A)))):
        o = B[:]; R.shuffle(o)
        add(s, g, mk(t, q, x, [(b, f"“{b}” {lb}") for b, lb in o[:3]], f"“{x}” {la}"))

